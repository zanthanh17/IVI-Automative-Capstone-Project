static const char *ButtonNameFromId(uint8_t id)
{
  switch (id)
  {
    case 1: return "left_signal";
    case 2: return "right_signal";
    case 3: return "headlight";
    case 4: return "horn";
    case 5: return "door_open";
    case 6: return "seatbelt";
    default: return "unknown";
  }
}

