  GPIO_Handler_Init();
  Encoder_Init();

  /* Boot message - xác nhận firmware đang chạy */
  {
    const char *boot_msg = "\r\n=== IVI Automative CP Started ===\r\n";
    HAL_UART_Transmit(&huart1, (uint8_t *)boot_msg, strlen(boot_msg), 100);
  }
  /* USER CODE END 2 */

