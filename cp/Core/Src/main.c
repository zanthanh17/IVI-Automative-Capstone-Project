/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* MCU Configuration--------------------------------------------------------*/
  HAL_Init();
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_CAN_Init();

  /* USER CODE BEGIN 2 */
  Body_Loads_Init();
  Body_CAN_Init();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    uint32_t now = HAL_GetTick();

    Body_Loads_Service(now);
    Body_CAN_Service(now);

    if ((now - s_heartbeat_tick) >= BODY_HEARTBEAT_MS) {
      HAL_GPIO_TogglePin(BODY_HEARTBEAT_GPIO_Port, BODY_HEARTBEAT_Pin);
      s_heartbeat_tick = now;
    }

    HAL_Delay(BODY_MAIN_LOOP_DELAY_MS);
  }
  /* USER CODE END WHILE */
}

